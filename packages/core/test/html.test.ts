test('an arXiv paper (LaTeXML HTML): headings, math from alttext, numbered equations, footnotes, tables, references', () => {
  const page = htmlToMarkdown(fixture('arxiv-latexml.html'), { url: 'https://ar5iv.labs.arxiv.org/html/1706.03762' });
  assert.equal(page.title, 'Attention Is All You Need');
  const md = page.markdown;
  const blocks = splitBlocks(md);
  assert.equal(blocks[0], '# Attention Is All You Need');
  assert.ok(blocks.includes('###### Abstract'));
  assert.ok(blocks.includes('## 3 Model Architecture'));
  assert.ok(blocks.includes('#### 3.2.1 Scaled Dot-Product Attention'));
  // Inline math keeps its LaTeX.
  assert.match(md, /queries and keys of dimension \$d_\{k\}\$, and values of dimension \$d_\{v\}\$\./);
  // An equation table is the formula, numbered.
  assert.ok(
    blocks.includes(
      '$$\n\\mathrm{Attention}(Q,K,V)=\\mathrm{softmax}(\\frac{QK^{T}}{\\sqrt{d_{k}}})V \\tag{1}\n$$',
    ),
    md,
  );
  // The footnote: a mark in the sentence, the note right after the paragraph.
  const para = blocks.find((b) => b.startsWith('We suspect that')) as string;
  assert.match(para, /extremely small gradients⁴\. To counteract this effect/);
  const note = blocks[blocks.indexOf(para) + 1] as string;
  assert.match(note, /^> ⁴ To illustrate why the dot products get large/);
  assert.match(note, /\$q\\cdot k=\\sum_\{i=1\}\^\{d_\{k\}\}q_\{i\}k_\{i\}\$, has mean \$0\$ and variance \$d_\{k\}\$\./);
  // Figures keep their caption; images go.
  assert.ok(blocks.some((b) => b.startsWith('*Figure 2: (left) Scaled Dot-Product Attention.')));
  assert.ok(!md.includes('x2.png') && !md.includes('Refer to caption'));
  // A table with math in its cells.
  assert.ok(
    blocks.includes(
      '| Layer Type | Complexity per Layer |\n| --- | --- |\n| Self-Attention | $O(n^{2}\\cdot d)$ |\n| Recurrent | $O(n\\cdot d^{2})$ |',
    ),
    md,
  );
  assert.ok(blocks.some((b) => b.startsWith('*Table 1: Maximum path lengths')));
  // References stay; page furniture, the table of contents and scripts go.
  assert.ok(blocks.includes('## References'));
  assert.match(md, /- \\\[1\\\]Jimmy Lei Ba, Jamie Ryan Kiros, and Geoffrey E Hinton\. Layer normalization\./);
  for (const gone of ['View original', 'Generated by', 'mathjax', 'ltx_page_main', 'Introduction']) {
    assert.ok(!md.includes(gone), gone);
  }
  // Authors, with their lines.
  assert.match(md, /Ashish Vaswani\\\nGoogle Brain\\\n`avaswani@google.com`|Ashish Vaswani\\\nGoogle Brain\\\navaswani@google\.com/);
});

test('an article: the article only, with emphasis, links, code, nested and numbered lists, quotes and safe text', () => {
  const page = htmlToMarkdown(fixture('blog.html'), { url: 'https://blog.example/posts/scale' });
  assert.equal(page.title, 'Why scale by √d?');
  const blocks = splitBlocks(page.markdown);
  assert.equal(blocks[0], '# Why scale by √d?');
  assert.ok(blocks.includes('By A. Writer · 3 min read'));
  assert.ok(
    blocks.includes(
      'Dot products of *random* vectors grow with their dimension — **roughly like √d**. See [the variance post](https://blog.example/posts/variance) & notes.',
    ),
    page.markdown,
  );
  assert.ok(blocks.includes('## A quick check'));
  assert.ok(
    blocks.includes(
      '```python\nimport numpy as np\nq, k = np.random.randn(2, 512)\n\nprint(q @ k)  # about sqrt(512) in size\n```',
    ),
  );
  assert.ok(page.markdown.includes('Things to remember:\n\n- Mean is 0.\n- Variance is `d`.\n  - So the std is √d.\n\n3. Third\n4. Fourth\n\n'));
  assert.ok(blocks.includes('> Softmax saturates when its inputs are large.'));
  assert.ok(blocks.includes('Prices like \\$5 and 2\\*3 and snake\\_case stay literal.'));
  assert.ok(blocks.includes('Inline TeX from MathJax: $\\sqrt{d_k}$ and a display one:'));
  assert.ok(blocks.includes('$$\n\\sum_i q_i k_i\n$$'));
  assert.ok(blocks.includes('\\1. Not a list, just a sentence that starts with a number.'));
  for (const gone of ['cookies', 'About', 'Related', 'Share', '© 2026', 'analytics']) {
    assert.ok(!page.markdown.includes(gone), gone);
  }
});

