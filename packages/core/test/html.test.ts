test('pasted fragments and broken HTML still come out readable', () => {
  // A fragment copied from a page: no <html>, unclosed <p> and <li>.
  const md = htmlToMarkdown('<h3>Notes</h3><p>First point<p>Second <i>point</i><ul><li>one<li>two</ul>').markdown;
  assert.deepEqual(splitBlocks(md), ['### Notes', 'First point', 'Second *point*', '- one\n- two']);
  // Chinese text, a stray end tag, a comment and CDATA.
  const zh = htmlToMarkdown('<p>注意力机制<!-- note -->的方差</p></div><p><![CDATA[x < y]]></p>').markdown;
  assert.deepEqual(splitBlocks(zh), ['注意力机制的方差', 'x \\< y']);
  assert.deepEqual(htmlToMarkdown('').markdown, '');
  assert.deepEqual(htmlToMarkdown('plain text, no tags').markdown, 'plain text, no tags');
});

